#!/usr/bin/env python3
"""Reduce Natural Earth 1:50m admin-0 countries to src/data/countries.{json,js}.

Usage (from the project root):
  mkdir -p tools/raw && curl -sL -o tools/raw/ne50.geojson \
    https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
  python3 -I tools/build_countries.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'raw', 'ne50.geojson')
OUT_JSON = os.path.join(ROOT, 'src', 'data', 'countries.json')
OUT_JS = os.path.join(ROOT, 'src', 'data', 'countries.js')

# NE ISO_A2 is "-99" for some entries; ISO_A2_EH fixes most. Manual overrides by ADM0_A3.
CODE_FIX = {'SOL': 'SO', 'CYN': 'CY'}   # merged into their parent country
SKIP_A3 = {'IOA', 'ATC', 'KAS', 'ATF', 'HMD', 'SGS', 'IOT'}  # tiny/uninhabited/disputed bits
NAME_FIX = {
    'United States of America': 'United States', 'Czech Republic': 'Czechia',
    'Ivory Coast': 'Ivory Coast', 'East Timor': 'Timor-Leste',
    "People's Republic of China": 'China', 'Federated States of Micronesia': 'Micronesia',
    'The Bahamas': 'Bahamas', 'The Gambia': 'Gambia', 'Republic of the Congo': 'Republic of the Congo',
    'Palestine': 'Palestine', 'Macau': 'Macau', 'Cape Verde': 'Cape Verde',
}
CONT_FIX = {'SC': 'Africa', 'MU': 'Africa', 'MV': 'Asia', 'SH': 'Africa'}
DROP_CODES = {'AQ'}

R = 3


def rnd_ring(ring):
    out = []
    for x, y in ring:
        p = [round(x, R), round(y, R)]
        if not out or out[-1] != p:
            out.append(p)
    if len(out) > 1 and out[0] != out[-1]:
        out.append(out[0])
    return out


def reduce_poly(poly):
    outer = rnd_ring(poly[0])
    if len(outer) < 4:
        return None
    holes = [h for h in (rnd_ring(r) for r in poly[1:]) if len(h) >= 4]
    return [outer] + holes


def polys_of(geom):
    return [geom['coordinates']] if geom['type'] == 'Polygon' else geom['coordinates']


def bbox_of(polys):
    xs = [p[0] for poly in polys for p in poly[0]]
    ys = [p[1] for poly in polys for p in poly[0]]
    return [min(xs), min(ys), max(xs), max(ys)]


def main():
    with open(SRC) as f:
        feats = json.load(f)['features']
    by_code = {}
    order = []
    for ft in feats:
        p = ft['properties']
        a3 = p['ADM0_A3']
        if a3 in SKIP_A3:
            continue
        code = CODE_FIX.get(a3) or p['ISO_A2_EH']
        if code in ('-99', '', None):
            code = p['ISO_A2']
        if code in ('-99', '', None):
            raise SystemExit('no code for ' + p['NAME'])
        if code in DROP_CODES:
            continue
        polys = [q for q in (reduce_poly(x) for x in polys_of(ft['geometry'])) if q]
        if not polys:
            continue
        if code in by_code:
            by_code[code]['polys'].extend(polys)
            continue
        name = p['NAME_EN']
        name = NAME_FIX.get(name, name)
        cont = CONT_FIX.get(code, p['CONTINENT'])
        by_code[code] = {'code': code, 'name': name, 'continent': cont, 'polys': polys}
        order.append(code)
    data = []
    for code in sorted(order, key=lambda c: by_code[c]['name']):
        c = by_code[code]
        polys = c['polys']
        geom = ({'type': 'Polygon', 'coordinates': polys[0]} if len(polys) == 1
                else {'type': 'MultiPolygon', 'coordinates': polys})
        data.append({'code': code, 'name': c['name'], 'continent': c['continent'],
                     'bbox': [round(v, R) for v in bbox_of(polys)], 'geometry': geom})
    txt = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    with open(OUT_JSON, 'w') as f:
        f.write(txt)
    with open(OUT_JS, 'w') as f:
        f.write('// Generated by tools/build_countries.py from Natural Earth 1:50m (public domain).\n')
        f.write('export default ' + txt + ';\n')
    print(len(data), 'countries', os.path.getsize(OUT_JSON), 'bytes')


main()
